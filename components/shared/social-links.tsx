/** Display order. */
const order: SocialNetwork[] = ["linkedin", "facebook", "instagram", "youtube", "x", "github"];

export function getSocialLinks() {
  return order
    .filter((n) => !isPlaceholder(siteConfig.social[n]))
    .map((n) => ({ network: n, href: siteConfig.social[n], ...glyphs[n] }));
}

/** Icon row of the company's social profiles. Renders nothing until a URL is set. */
export function SocialLinks({ className, size = "md" }: { className?: string; size?: "sm" | "md" }) {
  const links = getSocialLinks();
  if (links.length === 0) return null;
  return (
    <ul className={cn("flex flex-wrap gap-2", className)} aria-label="Syntram on social media">
      {links.map((l) => (
        <li key={l.network}>
          <a
            href={l.href}
            target="_blank"
            rel="noopener noreferrer"
            aria-label={`${siteConfig.shortName} on ${l.label} (opens in a new tab)`}
            data-track-cta={`social_${l.network}`}
            className={cn(
              "grid place-items-center rounded-lg border border-line-strong text-muted-foreground transition-colors hover:border-signal hover:text-signal",
              size === "sm" ? "size-9" : "size-11",
            )}
          >
            <svg viewBox="0 0 24 24" aria-hidden="true" className={size === "sm" ? "size-4" : "size-[1.125rem]"} fill="currentColor">
              <path d={l.path} />
            </svg>
          </a>
        </li>
      ))}
    </ul>
  );
}
